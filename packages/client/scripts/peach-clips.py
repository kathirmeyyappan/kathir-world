"""Builds render/avatars/peachClips.ts: how Peach moves where Super Mario 64's Mario won't do for
her, as Super Smash Bros. Brawl moved her.

    pip install numpy
    python packages/client/scripts/peach-clips.py path/to/FitPeach00.pcs path/to/FitPeachMotionEtc.pac

The source is Peach's own files from Brawl (brawl.py reads them): her model, for its skeleton,
which is bound in a T-pose, and her animations, 60 frames a second. The ones here are Project M's
copy of them, whose movement is Brawl's frame for frame but for a retouched jump. This takes the
handful CLIPS lists and carries each onto a jointed body's skeleton as clips.py says, her waist
left out as Mario's is (the jointed body's spine is halfway between its hips and its chest). The
fighter's travel across the floor, which an animation keeps on a bone of its own, is left out: the
clips stay where they stand.

In the air the game draws her higher than an animation's frames have her, her feet tucked up
under her skirt: by AIR_LIFT, measured against the game's own frames as rukaidata.com shows them.

A stride is turned round to start as its right foot is furthest ahead, where it comes down: her
feet hardly leave the floor, so there is no telling by their height.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

import brawl
import numpy as np
from clips import BONES, CLIENT, T_POSE, Carrier, Frame, written

# The source's bone each of the jointed body's takes, and for the ones a T-pose turns, the bone
# its own runs to.
JOINTS = {
    "hips": "HipN",
    "spine": "WaistN",
    "chest": "BustN",
    "head": "HeadN",
    "armL": "LShoulderJ",
    "forearmL": "LArmJ",
    "handL": "LHandN",
    "armR": "RShoulderJ",
    "forearmR": "RArmJ",
    "handR": "RHandN",
    "legL": "LLegJ",
    "shinL": "LKneeJ",
    "footL": "LFootJ",
    "legR": "RLegJ",
    "shinR": "RKneeJ",
    "footR": "RFootJ",
}
ENDS = {
    "armL": "LArmJ",
    "forearmL": "LHandN",
    "handL": "L2ndNa",
    "armR": "RArmJ",
    "forearmR": "RHandN",
    "handR": "R2ndNa",
    "legL": "LKneeJ",
    "shinL": "LFootJ",
    "legR": "RKneeJ",
    "shinR": "RFootJ",
}
TRAVEL = ("TransN",)  # the bone a fighter's travel is on
AIR_LIFT = 0.43  # leg lengths


@dataclass(frozen=True)
class Clip:
    source: str  # the animation's name
    first: int  # its frames, first to last
    last: int
    every: int = 2  # every how many of them are kept
    stride: bool = False  # a walk's cycle: turned round to start as the right foot comes down
    air: bool = False  # off the ground: drawn AIR_LIFT higher


CLIPS = {
    # Standing: her hands folded, swaying. A cycle's last frame is its first again, and is left out.
    "idle": Clip("Wait1", 0, 99, 4),
    # Her walk and, in a run's place, her quick walk: small steps under the skirt.
    "walk": Clip("WalkMiddle", 0, 39, stride=True),
    "run": Clip("WalkFast", 0, 59, stride=True),
    "jump": Clip("JumpF", 0, 20, air=True),
    "fall": Clip("Fall", 0, 7, air=True),
    "land": Clip("LandingLight", 3, 15),
    # Floating: held up, her feet kicking under her.
    "float": Clip("Fuwafuwa", 0, 47, air=True),
}


def main(model_path: str, motion_path: str) -> None:
    model = brawl.unpacked(Path(model_path).read_bytes())
    skeleton = brawl.bones(model, brawl.tagged(model, b"MDL0")[0])
    motion = brawl.unpacked(Path(motion_path).read_bytes())
    animations = {a.name: a for a in (brawl.animation(motion, at) for at in brawl.tagged(motion, b"CHR0"))}

    def posed(moving: brawl.Animation | None, frame: int) -> dict[str, np.ndarray]:
        world = brawl.pose(skeleton, moving, frame, TRAVEL)
        out = {}
        for bone, joint in JOINTS.items():
            m = world[joint].copy()
            m[:3, :3] /= np.linalg.norm(m[:3, :3], axis=0)
            out[bone] = m
        return out

    bound = brawl.pose(skeleton, None, 0)
    along = {}
    for bone, end in ENDS.items():
        way = bound[end][:3, 3] - bound[JOINTS[bone]][:3, 3]
        along[bone] = way / np.linalg.norm(way)
    carrier = Carrier("peach", posed(None, 0), along)

    lines = [
        "// Generated by packages/client/scripts/peach-clips.py from Peach's files in Super Smash Bros. Brawl; don't edit.",
        "// Brawl's own animations of her, carried onto a jointed body's skeleton (Jointed.ts), in the layout",
        "// marioClips.ts has. A stride starts as the right foot comes down, and its left comes down halfway.",
        "export const PEACH_CLIPS = {",
        f"  bones: [{', '.join(repr(b) for b, _ in BONES)}],",
    ]
    for name, clip in CLIPS.items():
        moving = animations[clip.source]
        poses = [posed(moving, k) for k in range(clip.first, clip.last + 1)]
        frames: list[Frame] = [carrier.frame(pose) for pose in poses]
        if clip.air:
            frames = [(hips + np.array([0, AIR_LIFT, 0]), turns, off) for hips, turns, off in frames]
        if clip.stride:
            ahead = [float(pose["footR"][2, 3] - pose["hips"][2, 3]) for pose in poses]
            start = int(np.argmax(ahead))
            frames = frames[start:] + frames[:start]
            other = int(np.argmax([float(pose["footL"][2, 3] - pose["hips"][2, 3]) for pose in poses]))
            print(f"{name}: right foot down on frame {clip.first + start}, left {((other - start) % len(poses)) / len(poses):.2f} of the way on")
        lines += written(name, frames[:: clip.every], brawl.FPS / clip.every)
    lines += ["} as const;", ""]
    out = CLIENT / "src/render/avatars/peachClips.ts"
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
